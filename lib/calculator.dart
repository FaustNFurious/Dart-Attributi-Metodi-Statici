class Calculator {
  // Metodo Statico per sommare due numeri
  static int add(int a, int b) {
    return a + b;
  }

  // Metodo Statico per sottrarre due numeri
  static int subtract(int a, int b) {
    return a - b;
  }

  // Metodo Statico per moltiplicare due numeri
  static int multiply(int a, int b) {
    return a * b;
  }

  // Metodo Statico per dividere due numeri
  static double divide(int a, int b) {
    return a / b;
  }

}